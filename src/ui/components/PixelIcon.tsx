export type IconName = keyof typeof ICONS

function runs(rows: string[]): { x: number; y: number; w: number }[] {
  const out: { x: number; y: number; w: number }[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1
        while (row[x + w] === '#') w++
        out.push({ x, y, w })
        x += w
      } else x++
    }
  })
  return out
}

const cache = new Map<IconName, { x: number; y: number; w: number }[]>()

export interface PixelIconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName
  /** Rendered size in px; keep it a multiple of 10 for crisp pixels. */
  size?: number
  /** Accessible label. Without it the icon is decorative (aria-hidden). */
  label?: string
}

export function PixelIcon({ name, size = 20, label, ...rest }: PixelIconProps) {
  let r = cache.get(name)
  if (!r) {
    r = runs(ICONS[name])
    cache.set(name, r)
  }
  return (
    <svg
      viewBox="0 0 10 10"
      width={size}
      height={size}
      fill="currentColor"
      shapeRendering="crispEdges"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      {...rest}
    >
      {r.map((p, i) => (
        <rect key={i} x={p.x} y={p.y} width={p.w} height={1} />
      ))}
    </svg>
  )
}
